"""
   node_pdf_to_md 
     Input: state [is_pdf_read_enabled = True | pdf_path = xxx.pdf | local_dir = output]
     Output: state [md_path = file path | md_content = Markdown content]
     1. Record logs and task status.
     2. Validate paths with step_1_validate_paths.
     3. Upload the PDF to MinerU and poll for results with step_2_upload_and_poll.
     4. Download and extract the Markdown archive with step_3_download_and_extract.
     5. Record logs and task status, then return state.
   step_1_validate_paths
     Input: state pdf_path = xxx.pdf | local_dir = output
     Output: pdf_path_obj Path, local_output_dir_obj Path
     1. Ensure required values are not empty.
     2. Verify the PDF exists; use the default output directory when local_dir is missing.
     3. Return usable Path objects.
   step_2_upload_and_poll
     Input: pdf_path_obj, the Path of the PDF file.
     Output: str, the download URL for the result zip file.
     1. Request an upload URL from MinerU.
     2. Upload the PDF with a requests session and PUT.
     3. Poll for the result zip URL. Use a max wait time, poll every 3 seconds, and tolerate 5xx responses until timeout.
     4. Return the result URL.
   step_3_download_and_extract
     Input: zip_url, out_dir_obj, and the original file name from path.stem.
     Output: str path to the extracted .md file.
     1. Download the zip file to output / stem_result.zip.
     2. Prepare the extraction folder at output / stem.
     3. Remove any existing extraction folder to avoid stale files.
     4. Extract the zip file with ZipFile.extractall(target_dir).
     5. Select the Markdown file by original name, full.md, or the first available .md file.
     6. Rename the selected file to the original file name.
     7. Return the absolute Markdown path as a string.
"""

def step_1_validate_paths(state):
    """
    Validate input paths.

    Raise an error when pdf_path is invalid. Use the default output directory
    when local_dir is not provided.
    :param state:
    :return:
    """
    logger.debug(f">>> [step_1_validate_paths] Starting PDF-to-Markdown path validation.")
    pdf_path = state['pdf_path']
    local_dir = state['local_dir']
    
    # Basic non-empty validation for string inputs.
    if not pdf_path:
        logger.error("[step_1_validate_paths] No input PDF file was provided; parsing cannot continue.")
        raise ValueError("[step_1_validate_paths] No input PDF file was provided; parsing cannot continue.")
    
    if not local_dir:
        # Use the default output directory when none is provided.
        local_dir = PROJECT_ROOT / "output"
        logger.info(f"[step_1_validate_paths] local_dir was not provided; using default: {local_dir}")
    # Validate that the input file and output directory exist.
    # pdf is built to a job
    pdf_path_obj = Path(pdf_path)
    local_output_dir_obj = Path(local_dir)

    if not pdf_path_obj.exists():
        logger.error(f"[step_1_validate_paths] pdf_path does not exist; please check the input file path.")
        raise FileNotFoundError(f"[step_1_validate_paths] pdf_path does not exist; please check the input file path.")
    if not local_output_dir_obj.exists():
        logger.error(f"[step_1_validate_paths] local_dir does not exist; creating the output directory.")
        local_output_dir_obj.mkdir(parents=True, exist_ok=True)

    return pdf_path_obj, local_output_dir_obj


def step_2_upload_and_poll(pdf_path_obj)->str:
    """
    Parse the PDF with MinerU and return the Markdown zip download URL.
    :param pdf_path_obj: Path object for the PDF file to parse.
    :return: str -> URL for the Markdown zip generated by MinerU.
    """

    # 1. Request the upload URL for this PDF.
    # Prepare the API URL, token, and required request headers.
    token = mineru_config.api_key
    url = f"{mineru_config.base_url}/file-urls/batch"
    header = {
        "Content-Type": "application/json",
        "Authorization": f"Bearer {token}"
    }
    data = {
        "files": [
            # get the pdf name
            {"name": f"{pdf_path_obj.name}"}
        ],
        "model_version": "vlm"
    }
    response = requests.post(url, headers=header, json=data)
    # Treat non-200 HTTP responses or non-zero API codes as request failures.
    if response.status_code != 200 or response.json()['code'] != 0:
        logger.error(f"[step_2_upload_and_poll] Failed to request the MinerU parsing API; please check the input file path.")
        raise RuntimeError(f"[step_2_upload_and_poll] Failed to request the MinerU parsing API; please check the input file path.")

    # get the upload URL
    uploaded_url = response.json()['data']['file_urls'][0] # Upload the file to this URL.

    # batch id, it is used to fetch the result after the file is parsed.
    batch_id = response.json()['data']['batch_id'] # Use this batch ID to fetch the result later.

    # 2. Upload the PDF to the provided parsing URL.
    # Use PUT to send the PDF file content to uploaded_url.
    # Do not rely on environment proxy settings here. Proxies may add extra PUT headers,
    # and the third-party storage service can reject the upload because it validates PUT requests strictly.
    http_session = requests.Session()
    http_session.trust_env = False # Disable proxies and reuse the session.
    try:
        with open(pdf_path_obj,'rb') as f:
            file_data = f.read()

        # Upload the PDF to the provided parsing URL.
        upload_response = http_session.put(uploaded_url, data=file_data)

        if upload_response.status_code != 200:
            logger.error(f"[step_2_upload_and_poll] Failed to upload the file to MinerU; please check the input file path.")
            raise RuntimeError(f"[step_2_upload_and_poll] Failed to upload the file to MinerU; please check the input file path.")
    except Exception as e:
        logger.error(f"[step_2_upload_and_poll] Failed to upload the file to MinerU; please check the input file path.")
        raise RuntimeError(f"[step_2_upload_and_poll] Failed to upload the file to MinerU; please check the input file path.")
    finally:
        http_session.close()

    # 3. Poll until the parsing result is ready.
    # Check every 3 seconds and wait up to 10 minutes. The timeout assumes about 1 second per PDF page.
    url = f"{mineru_config.base_url}/extract-results/batch/{batch_id}"
    timeout_seconds = 600  # Estimate: 1 second per PDF page. 600 seconds can parse 600 pges
    poll_interval = 3  # Poll every 3 seconds.
    start_time = time.time() # Polling start time.

    while True:
        # 3.1 Stop polling after the overall timeout is reached.
        if time.time() - start_time > timeout_seconds:
            logger.error("[step_2_upload_and_poll] MinerU parsing request timed out; please check the input file path.")
            raise TimeoutError("[step_2_upload_and_poll] MinerU parsing request timed out; please check the input file path.")
        # 3.2 Fetch the current parsing result.
        res = requests.get(url, headers=header)
        # 3.3 Validate the result and extract the zip URL.
        if res.status_code != 200:
            # Retry 5xx server errors until timeout.
            # HTTP status groups: 1xx, 2xx, 3xx, 4xx, 5xx.
            if 500 <= res.status_code < 600:
                time.sleep(poll_interval)
                continue
            raise RuntimeError(f"[step_2_upload_and_poll] MinerU parsing request failed with HTTP status code {res.status_code}.")

        json_data = res.json() # Current result payload.
        if json_data['code'] != 0:
           # A non-zero code usually means the token is invalid, expired, or the account has no remaining quota.
           raise RuntimeError(f"[step_2_upload_and_poll] MinerU parsing request failed with error code {json_data['code']}: {json_data['msg']}")

        # Check whether parsing has finished.
        extract_result = json_data['data']['extract_result'][0]
        if extract_result['state'] == 'done':
            # Parsing is complete, so the result URL is available.
            full_zip_url = extract_result['full_zip_url']
            logger.info(f"PDF parsing completed in {time.time()-start_time}s. Result URL: {full_zip_url}")
            # return the result URL after the extract_result['state'] == 'done'
            return full_zip_url
        else:
            # Parsing is still in progress.
            time.sleep(poll_interval)

def step_3_download_and_extract(zip_url, local_output_dir_obj, stem) -> str:
    """
    Download the Markdown zip file, extract it, and return the extracted Markdown path.
    :param zip_url: URL to download.
    :param local_output_dir_obj: Output directory.
    :param stem: PDF file name without extension.
    :return: Path to the Markdown file.
    """
    # 1. Download the zip file.
    response = requests.get(zip_url)

    if response.status_code != 200:
        logger.error(f"[step_3_download_and_extract] Failed to download the file; please check the input file path.")
        raise RuntimeError(f"[step_3_download_and_extract] Failed to download the file; please check the input file path.")
    # 2. Save the zip response body locally.
    # Example output path: output/<stem>_result.zip.
    zip_save_path = local_output_dir_obj / f"{stem}_result.zip"
    with open(zip_save_path, 'wb') as f:
        # response.content contains the response body bytes.
        f.write(response.content)
    logger.info(f"[step_3_download_and_extract] File downloaded successfully. Saved to: {zip_save_path}")

    # 3. Remove any existing extraction directory from a previous run.
    extract_target_dir = local_output_dir_obj /  stem
    # Clear old files first because repeated extractions may contain different file sets.
    if extract_target_dir.exists():
        # Recursively remove both the directory contents and the directory itself.
        shutil.rmtree(extract_target_dir)
    # Create a clean extraction directory.
    extract_target_dir.mkdir(parents=True, exist_ok=True)
    # 4. Extract the zip file.
    # zipfile is Python's standard module for reading and writing zip archives.
    # ZipFile(zip_save_path, 'r') opens the zip archive in read-only mode for extraction.
    with zipfile.ZipFile(zip_save_path, 'r') as zip_file_object:
        # Extract all files into the target directory, such as output/<stem>.
        zip_file_object.extractall(extract_target_dir)
    # 5. Return the Markdown file path.
    # The extracted Markdown may use the original file name, full.md, or another name.
    md_file_list = list(extract_target_dir.rglob("*.md"))

    if not md_file_list:
        logger.error(f"[step_3_download_and_extract] No Markdown file was found; please check the input file path.")
        raise RuntimeError(f"[step_3_download_and_extract] No Markdown file was found; please check the input file path.")

    target_md_file = None # Final Markdown file.
    # Prefer a Markdown file that matches the original PDF file name.
    for md_file in md_file_list:
        # stem is the original PDF file name without extension.
        if md_file.name == stem + ".md":
            target_md_file = md_file
            break
    # If not found, try full.md.
    if not target_md_file:
        for md_file in md_file_list:
            # MinerU may output full.md depending on its version.
            if md_file.name.lower() == "full.md":
                target_md_file = md_file
                break
    # Fallback to the first Markdown file.
    if not target_md_file:
        target_md_file = md_file_list[0]

    # Normalize the Markdown file name to <stem>.md.
    # Rename only when the selected file does not already use the expected stem.
    if target_md_file.stem != stem:
        # Build the renamed path, then rename the file on disk and return the new Path.
        target_md_file = target_md_file.rename(target_md_file.with_name(f"{stem}.md"))

    # Resolve the final Markdown file to an absolute path and return it as a string.
    final_md_str_path = str(target_md_file.resolve())
    logger.info(f"[step_3_download_and_extract] Markdown extraction completed. Final Markdown path: {final_md_str_path}")
    return final_md_str_path


def node_pdf_to_md(state: ImportGraphState) -> ImportGraphState:
    """
    Node: PDF to Markdown (node_pdf_to_md).
    Purpose: Convert unstructured PDF data into structured Markdown data.
    Workflow:
        1. Record start logs and task status.
        2. Validate inputs. Use a default local_dir when missing, and verify that the PDF file exists.
        3. Send the PDF to MinerU and get the result zip download URL.
        4. Download, extract, and locate the Markdown file.
        5. Store md_path and read the Markdown text into md_content.
        6. Record finish logs and task status.
        Error handling is centralized with try/except.
    """
    # 1. Record start logs and task status.
    function_name = sys._getframe().f_code.co_name
    logger.info(f">>> [{function_name}] Started. Current state: {state}")
    add_running_task(state['task_id'], function_name)


    try:
        # 2. Validate inputs and return Path objects for the PDF and output directory.
        # Input: state with local_file_path and local_dir.
        # Output: validated file path (pdf_path_obj) and output directory Path (local_output_dir_obj) objects.
        pdf_path_obj, local_output_dir_obj = step_1_validate_paths(state)
        # 3. Send the PDF to MinerU and return the zip download URL.
        # Input: PDF path. Output: zip file URL.
        zip_url = step_2_upload_and_poll(pdf_path_obj)
        # 4. Download and extract the zip file.
        # Inputs: zip URL, extraction directory, and original PDF file name.
        # Output: actual path to the extracted Markdown file.
        # pdf_path_obj.stem means remove the extension
        md_path = step_3_download_and_extract(zip_url, local_output_dir_obj, pdf_path_obj.stem)
        # 5. Store md_path and read the Markdown content into md_content.
        # Update state data. md_path: makedown file's path
        # local_dir: output dir
        state['md_path'] = md_path # TODO: keep this as a string.
        state['local_dir'] = str(local_output_dir_obj) # Keep local_dir as a string in state.
        # Read the Markdown file content into md_content.

        with open(md_path, 'r', encoding='utf-8') as f:
            state['md_content'] = f.read()

    except Exception as e:
        # Log the error and stop the workflow.
        logger.error(f">>> [{function_name}] MinerU parsing failed with error: {e}")
        raise # Stop the workflow.

    finally:
        # 6. Record finish logs and task status.
        logger.info(f">>> [{function_name}] Finished. Current state: {state}")
        add_done_task(state['task_id'], function_name)

    return state






